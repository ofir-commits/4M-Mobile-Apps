/* =========================================================
   Shilo Pro — Customer area JS
   Login/recover panel toggle, address forms, country selects, order print
   ========================================================= */
(function () {
  'use strict';

  /* ---------- Login <-> recover panel toggle ---------- */
  document.addEventListener('click', (e) => {
    const trigger = e.target.closest('[data-auth-show]');
    if (!trigger) return;
    const wrap = document.querySelector('[data-auth-panels]');
    if (!wrap) return;
    e.preventDefault();
    const name = trigger.getAttribute('data-auth-show');
    wrap.setAttribute('data-active-panel', name);
    /* Clear a stale fragment (e.g. #recover set by the pre-JS anchor fallback):
       the CSS :target rules would otherwise keep the recover panel open. A real
       fragment navigation is required — history.replaceState does not recompute
       the document's :target element. */
    if (window.location.hash && window.location.hash !== '#' + name) {
      window.location.replace('#' + name);
    }
    const panel = wrap.querySelector('[data-auth-panel="' + name + '"]');
    panel?.querySelector('input:not([type="hidden"])')?.focus({ preventScroll: false });
  });

  function applyAuthHash() {
    const wrap = document.querySelector('[data-auth-panels]');
    if (wrap && window.location.hash === '#recover') {
      wrap.setAttribute('data-active-panel', 'recover');
    }
  }

  /* ---------- Address form show/hide toggles ---------- */
  document.addEventListener('click', (e) => {
    const trigger = e.target.closest('[data-address-toggle]');
    if (!trigger) return;
    e.preventDefault();
    const id = trigger.getAttribute('data-address-toggle');
    const target = document.getElementById(id);
    if (!target) return;
    const open = target.hasAttribute('hidden');
    target.toggleAttribute('hidden', !open);
    document.querySelectorAll('[data-address-toggle="' + id + '"]').forEach((btn) => {
      btn.setAttribute('aria-expanded', open ? 'true' : 'false');
    });
    if (open) {
      target.querySelector('input:not([type="hidden"]), select')?.focus({ preventScroll: true });
      target.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
    }
  });

  /* ---------- Print the current order ---------- */
  document.addEventListener('click', (e) => {
    const trigger = e.target.closest('[data-print-page]');
    if (!trigger) return;
    e.preventDefault();
    window.print();
  });

  /* ---------- Delete address confirmation ---------- */
  document.addEventListener('submit', (e) => {
    const form = e.target && e.target.closest ? e.target.closest('[data-address-delete]') : null;
    if (!form) return;
    const message = form.getAttribute('data-confirm-message');
    if (message && !window.confirm(message)) e.preventDefault();
  });

  /* ---------- Country / province selectors ---------- */
  /* province[1] below is a visible label that this theme cannot translate: the
     data-provinces payload is generated by Shopify and its province names are
     English in every locale, so writing it into option text puts English into a
     Hebrew form. main-addresses.liquid therefore ships a single Israel option with
     data-provinces="[]" (Israel has no provinces in Shopify's address schema), which
     makes the early return below the only path taken. The generic code is kept so
     the form still works if the country list is ever widened — but if it is, the
     province names must be mapped to Hebrew first. */
  function populateProvinces(countrySelect, provinceSelect, provinceContainer) {
    const option = countrySelect.options[countrySelect.selectedIndex];
    let provinces = [];
    try {
      provinces = JSON.parse((option && option.getAttribute('data-provinces')) || '[]');
    } catch (err) {
      provinces = [];
    }
    provinceSelect.innerHTML = '';
    if (!provinces.length) {
      if (provinceContainer) provinceContainer.style.display = 'none';
      return;
    }
    provinces.forEach((province) => {
      const opt = document.createElement('option');
      opt.value = province[0];
      opt.textContent = province[1];
      provinceSelect.appendChild(opt);
    });
    const preset = provinceSelect.getAttribute('data-default');
    if (preset) provinceSelect.value = preset;
    if (provinceContainer) provinceContainer.style.display = '';
  }

  function initCountrySelects() {
    document.querySelectorAll('[data-country-select]').forEach((select) => {
      if (select.dataset.initialized) return;
      select.dataset.initialized = 'true';
      const formId = select.getAttribute('data-form-id');
      const provinceSelect = document.getElementById('AddressProvince_' + formId);
      const provinceContainer = document.getElementById('AddressProvinceContainer_' + formId);

      /* Single-country form (the Israel-only case): there is nothing to select and
         no provinces to fetch, so skip Shopify's CountryProvinceSelector entirely
         rather than let it write English province names into the hidden field. */
      if (select.options.length <= 1) {
        if (provinceSelect) provinceSelect.innerHTML = '';
        if (provinceContainer) provinceContainer.style.display = 'none';
        return;
      }

      if (window.Shopify && window.Shopify.CountryProvinceSelector) {
        new window.Shopify.CountryProvinceSelector(
          'AddressCountry_' + formId,
          'AddressProvince_' + formId,
          { hideElement: 'AddressProvinceContainer_' + formId }
        );
        return;
      }

      /* Fallback: plain selects driven by data-provinces */
      const preset = select.getAttribute('data-default');
      if (preset) {
        Array.from(select.options).some((opt) => {
          if (opt.value === preset || opt.textContent === preset) {
            opt.selected = true;
            return true;
          }
          return false;
        });
      }
      if (provinceSelect) {
        populateProvinces(select, provinceSelect, provinceContainer);
        select.addEventListener('change', () => populateProvinces(select, provinceSelect, provinceContainer));
      }
    });
  }

  function init() {
    applyAuthHash();
    initCountrySelects();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
  document.addEventListener('shopify:section:load', init);
})();
